"""
Assemble the appendix option_geometry_tables.md (calibration fits, option tables, clearances, E1
variants) from the outputs of cam_calibrate.py, cam_report.py, cam_clearance.py and
cam_e1_variants.py, and write it next to option_geometry.md.

Usage: py -3.13 cam_appendix.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = r"D:\AI_Project\06_deliverables\research_notes\Camera mount options\option_geometry_tables.md"


def read(name: str) -> str:
    path = os.path.join(HERE, name)
    return open(path, encoding = "utf-8").read() if os.path.exists(path) else ""


def main() -> None:
    tables = read("cam_options_tables.md")
    clearance = read("cam_clearance_output.txt")
    variants = read("cam_e1_variants_output.txt")
    calibration = json.load(open(os.path.join(HERE, "cam_calibration.json")))
    text = ("# Camera options: full tables (appendix to option_geometry.md)\n\n"
            "Generated by cam_appendix.py from cam_calibration.json, cam_options_results.json (cam_options.py, 26.10.26), "
            "cam_clearance.py and cam_e1_variants.py. All numbers are computed (model) unless the row says measured. "
            "Headings are degrees from \"radially away from the base\", positive to the left. Radii are tip (rod end) "
            "distances from the base axis in metres. The 104 degree rows for options A to D are meaningless (the calibrated "
            "lens would sit in front of the puck) and are kept only for completeness.\n\n## Calibration fits (cam_calibrate.py)\n\n")
    for fov in sorted(calibration, key = lambda k: float(k.split("_")[1])):
        text += f"### {fov.replace('hfov_', '')} degrees\n\n"
        for key in ("window_fit", "pixel_fit", "pixel_fit_roll_zero", "combined_fit"):
            entry = calibration[fov][key]
            text += f"- {key}: " + ", ".join(f"{k} {v}" for k, v in entry.items() if k not in ("camera_parameters", "residual_cm")) + "\n"
        text += f"- lean20_check (recorded joints of 2026-10-25_lean20_orientation.json): {json.dumps(calibration[fov]['lean20_check'])}\n"
        text += f"- lean20 measured: {json.dumps(calibration[fov]['lean20_measured'])}\n\n"
    text += tables
    text += ("\n\n## Lens clearances (cam_clearance.py; forearm radius 3 cm and housing radius 2.3 cm assumed; worst pan of 0, +-90, +-145 deg; 52 deg designs)\n\n```\n"
             + clearance.strip() + "\n```\n\n## E1 collar variants (cam_e1_variants.py; 52 deg; tilt chosen to put the puck's leading edge at row 380 at pan 0; r = 0.26 m)\n\n```\n"
             + variants.strip() + "\n```\n")
    text = text.replace("np.float64(", "(").replace("np.float64", "")
    with open(TARGET, "w", encoding = "utf-8") as handle:
        handle.write(text)
    print("written", TARGET, len(text), "chars")


if __name__ == "__main__":
    main()
